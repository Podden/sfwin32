/* Sound: the Miles Sound System API, reimplemented on SDL audio.
 *
 * The game ships Miles 3.50F statically linked, driving a Sound Blaster
 * through an AIL3DIG driver -- 16-bit real-mode code that would need an 8086
 * interpreter plus DMA, DSP and IRQ emulation to run. None of that is
 * necessary: the driver is only the bottom of the stack. Hooking the AIL API
 * itself replaces the whole thing with a few hundred lines of mixer.
 *
 * Two things made this practical:
 *
 *  - MSS is built with a debug-logging facility, so every entry point carries
 *    a format string naming itself ("AIL_start_sample(0x%X)"). Each is
 *    referenced from inside the function it names, so the relocation table
 *    yields an exact symbol map -- see ../../ailmap.py.
 *  - Miles is compiled cdecl, not the Watcom register convention the game
 *    itself uses, so the hooks are ordinary C functions with no thunks.
 *
 * Sample data arrives as raw PCM with an explicit byte count -- see
 * h_set_sample_address below, where the call sites settle both the signature
 * and the signedness. Every sound effect is signed 8-bit mono (AIL format 0),
 * but the desktop's movie soundtracks turned out to be format 2 (16-bit
 * mono); AIL_set_sample_type's format code selects between all four Miles
 * formats (mono/stereo x 8/16-bit) rather than assuming one. Rate, volume,
 * pan and looping all come from the game through the API rather than from
 * any header.
 */

#include "port.h"
#include <SDL.h>
#include <string.h>

/* ---- AIL entry points (original link-time addresses) -------------------
 *
 * Verified by ailverify.py, which reads each wrapper's own debug format
 * string instead of pairing strings with the nearest preceding function.
 * That distinction is not academic: the adjacency heuristic in ailmap.py got
 * six of these wrong, and two were actively harmful -- one pointed at
 * AIL_release_sequence_handle, a MIDI call that was being answered with a
 * sample count. Re-run ailverify.py after editing this table; it exits
 * non-zero on any mismatch.
 *
 * The game ships two DOS/4GW binaries built from the same engine at different
 * link addresses, so there is one table per image. None of FIGHT's addresses
 * are valid in DESKTOP, and a 5-byte JMP at a wrong address corrupts whatever
 * really lives there -- which is precisely what happened on the first attempt
 * to load DESKTOP.EXE. Both tables are generated by ailtable.py, which names
 * each function from the string it pushes rather than from its neighbours.
 */
typedef enum {
    A_INSTALL_DIG_INI, A_UNINSTALL_DIG_DRIVER,
    A_ALLOCATE_SAMPLE_HANDLE, A_RELEASE_SAMPLE_HANDLE,
    A_INIT_SAMPLE, A_SET_SAMPLE_ADDRESS, A_SET_SAMPLE_TYPE,
    A_START_SAMPLE, A_END_SAMPLE, A_SET_SAMPLE_PLAYBACK_RATE,
    A_SET_SAMPLE_VOLUME, A_SET_SAMPLE_PAN, A_SET_SAMPLE_LOOP_COUNT,
    A_SAMPLE_STATUS, A_SET_DIGITAL_MASTER_VOLUME, A_SAMPLE_USER_DATA,
    A_COUNT
} ail_entry;

