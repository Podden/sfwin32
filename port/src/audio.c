#include <SDL.h>
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

/* ---- AIL entry points (original link-time addresses) -------------------
 *
 * Verified by ailverify.py, which reads each wrapper's own debug format
 * string instead of pairing strings with the nearest preceding function.
 * That distinction is not academic: the adjacency heuristic in ailmap.py got
 * six of these wrong, and two were actively harmful -- one pointed at
 * AIL_release_sequence_handle, a MIDI call that was being answered with a
 * sample count. Re-run ailverify.py after editing this table; it exits
 * non-zero on any mismatch.
 *
 * The game ships two DOS/4GW binaries built from the same engine at different
 * link addresses, so there is one table per image. None of FIGHT's addresses
 * are valid in DESKTOP, and a 5-byte JMP at a wrong address corrupts whatever
 * really lives there -- which is precisely what happened on the first attempt
 * to load DESKTOP.EXE. Both tables are generated by ailtable.py, which names
 * each function from the string it pushes rather than from its neighbours.
 */
